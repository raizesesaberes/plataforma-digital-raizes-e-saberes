class FakeAudio {
  paused = true; playCalls = 0; loads = 0;
  setAttribute() {}
  removeAttribute() { this.src = ''; }
  load() { this.loads++; }
  pause() { this.paused = true; }
  async play() { this.playCalls++; this.paused = false; }
}
async function playerFixture(options = {}) {
  const data = await fixture();
  const doc = new EventTarget(); doc.hidden = false;
  const win = new EventTarget(); win.location = {origin: 'https://example.test'};
  const events = [], audios = [], requests = [], revoked = [];
  let currentRegistry = data.registry;
  const player = new StaticNarrator({registry: () => currentRegistry, document: doc, window: win,
    onStatus: status => events.push(status), musicPlaying: () => false,
    fetch: async (...args) => { requests.push(args); return new Response(bytes); },
    makeAudio: () => { const audio = new FakeAudio(); audios.push(audio); return audio; },
    urls: {createObjectURL: () => 'blob:test-only', revokeObjectURL: url => revoked.push(url)}, ...options});
  player.setContext('activity:1', () => true);
  return {...data, player, doc, win, events, audios, requests, revoked,
    setRegistry: registry => { currentRegistry = registry; }};
}

