import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';

const source=readFileSync('app-pages.js','utf8');
const context={};vm.createContext(context);
vm.runInContext(source.slice(source.indexOf('const questionBankIsSynthetic ='),source.indexOf('const renderQuestionBankPreview ='))+'\nglobalThis.count=questionBankCountSummary;',context);
const authoral={id:'A',uuid:'uuid-A',legalClassification:'ITEM_AUTORAL_RAIZES_SABERES_ALINHADO_SAEB'};
const other={id:'B',uuid:'uuid-B',sourceName:'ENEM SAEB oficial',raw:{metadata:{enem:{canonicalItemId:'unverified'}}}};
const pilot=(id,canonical)=>({id,pilotSource:{id,demoOnly:true,selectionKey:canonical}});
const first=pilot('pilot:A','canonical-1'),bookletB=pilot('pilot:A-B','canonical-1'),second=pilot('pilot:B','canonical-2');
const catalog=[authoral,{...authoral,id:'another-code-same-uuid'},other,first,bookletB,second];
const plain=x=>JSON.parse(JSON.stringify(x));
let counts=plain(context.count(catalog,catalog,[authoral,first,bookletB]));
assert.deepEqual(counts.catalog,{total:4,real:2,synthetic:2,origins:{authoral:1,enem:0,saeb:0,other:1}});
assert.deepEqual(counts.filtered,counts.catalog);
assert.deepEqual(counts.selected,{total:2,real:1,synthetic:1,origins:{authoral:1,enem:0,saeb:0,other:0}});
counts=plain(context.count(catalog,[first,bookletB],[authoral,second]));
assert.equal(counts.catalog.total,4);
assert.equal(counts.filtered.total,1);
assert.equal(counts.filtered.real,0);
assert.equal(counts.selected.total,2,'filtering must not clear selection');
assert.equal(counts.selected.real,1);
counts=plain(context.count([authoral,other],[],[]));
assert.equal(counts.catalog.real,2);
assert.equal(counts.catalog.synthetic,0,'leaving the class removes its synthetic catalog');
assert.equal(counts.filtered.total,0);assert.equal(counts.selected.total,0);
counts=plain(context.count(catalog,catalog,catalog,true));
assert.equal(counts.catalog.real,0,'local demo data cannot be counted as real');
assert.equal(counts.catalog.synthetic,4);
const sameId=pilot('uuid-A','uuid-A');
assert.equal(context.count([authoral,sameId],[],[]).catalog.total,2,'synthetic and real identity namespaces do not collide');
assert.equal(context.count([{},null],[],[]).catalog.total,0,'unidentified occurrences are not new questions');
console.log('PASS counters: canonical booklet dedup, UUID/page dedup, origins reconcile, no inferred ENEM/SAEB, filters preserve selection, class reset, local demo excluded.');
